"""Trim, level and bundle picnic sound effects and a seamless night-ambience loop for the app."""
import json
from pathlib import Path
import shutil
import subprocess

import numpy

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "output" / "sound-effects"
DIRECTION = ROOT / "docs" / "PICNIC_SOUND_DIRECTION.json"
RUNTIME_AUDIO = ROOT / "assets" / "picnic" / "sound"
RUNTIME_MODULE = ROOT / "src" / "picnic-sound-clips.js"
RATE = 44100
EFFECT_PEAK_DBFS = -9.0      # voices are levelled to -18 LUFS / -1.5 dBTP; effects sit clearly underneath
AMBIENCE_LUFS = -26.0        # about 16 dB under speech in the app mix, then ducked a further ~10 dB while characters speak
LOOP_CROSSFADE_SECONDS = 1.5


def decode(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-f", "f32le", "-ac", "1", "-ar", str(RATE), "-"],
                         capture_output=True, check=True).stdout
    return numpy.frombuffer(raw, dtype=numpy.float32).copy()


def encode(samples, output, bitrate="64k", extra_filter=None):
    command = ["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ac", "1", "-ar", str(RATE), "-i", "-"]
    if extra_filter:
        command += ["-af", extra_filter]
    subprocess.run(command + ["-ac", "1", "-b:a", bitrate, str(output)], input=samples.astype(numpy.float32).tobytes(), check=True)


def measured_lufs(samples):
    """Integrated loudness of raw samples, measured by FFmpeg's EBU R128 meter."""
    result = subprocess.run(["ffmpeg", "-hide_banner", "-f", "f32le", "-ac", "1", "-ar", str(RATE), "-i", "-",
                             "-af", "loudnorm=print_format=json", "-f", "null", "-"],
                            input=samples.astype(numpy.float32).tobytes(), capture_output=True, check=True)
    text = result.stderr.decode("utf-8", "replace")
    return float(json.loads(text[text.rindex("{"):text.rindex("}") + 1])["input_i"])


def prepare_effect(samples):
    """Start on the first audible sound, fade the tail and set a consistent peak so no effect jumps out."""
    # Measured against this sound's own peak so soft sounds keep their natural tails.
    audible = numpy.flatnonzero(numpy.abs(samples) > numpy.max(numpy.abs(samples)) * 10 ** (-50 / 20))
    if not len(audible):
        raise ValueError("silent effect")
    trimmed = samples[max(0, audible[0] - int(.005 * RATE)):audible[-1] + int(.05 * RATE)]
    fade = min(len(trimmed), int(.04 * RATE))
    trimmed[-fade:] *= numpy.linspace(1, 0, fade)
    return trimmed * (10 ** (EFFECT_PEAK_DBFS / 20) / numpy.max(numpy.abs(trimmed)))


def prepare_ambience_loop(samples):
    """Blend the tail into the head so the loop point is continuous whether or not the provider made it seamless."""
    crossfade = int(LOOP_CROSSFADE_SECONDS * RATE)
    head, tail = samples[:crossfade], samples[-crossfade:]
    ramp = numpy.linspace(0, 1, crossfade)
    looped = samples[:-crossfade].copy()
    looped[:crossfade] = head * ramp + tail * (1 - ramp)
    # A fixed gain (not dynamic normalisation) keeps the night sounds steady instead of pumping.
    return looped * 10 ** ((AMBIENCE_LUFS - measured_lufs(looped)) / 20)


def prepare_picnic_sounds():
    direction = json.loads(DIRECTION.read_text(encoding="utf-8"))["sounds"]
    if RUNTIME_AUDIO.exists():
        shutil.rmtree(RUNTIME_AUDIO)
    RUNTIME_AUDIO.mkdir(parents=True)
    bundled = {}
    for name, sound in direction.items():
        original = SOURCE / "originals" / f"{name}.mp3"
        if not original.exists():
            print(f"Missing {name}; left silent in the app.")
            continue
        samples = decode(original)
        output = RUNTIME_AUDIO / f"{name}.mp3"
        if sound.get("loop"):
            encode(prepare_ambience_loop(samples), output)
        else:
            # 96 kbps keeps the high shimmer of bells and wicker that 64 kbps MP3 filters away.
            encode(prepare_effect(samples), output, "96k")
        duration = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(output)],
                                        capture_output=True, text=True, check=True).stdout)
        if not .1 < duration < 30:
            raise ValueError(f"{name}: unexpected duration {duration}")
        bundled[name] = {"file": f"./assets/picnic/sound/{name}.mp3", "duration": round(duration, 3)}
    RUNTIME_MODULE.write_text(
        "// Generated by scripts/prepare-picnic-sounds.py; do not edit by hand.\n"
        "// ElevenLabs sound generation from docs/PICNIC_SOUND_DIRECTION.json; effects peak at "
        f"{EFFECT_PEAK_DBFS:g} dBFS, ambience {AMBIENCE_LUFS:g} LUFS.\n"
        "export const PICNIC_SOUND_CLIPS=" + json.dumps(bundled, separators=(",", ":")) + ";\n", encoding="utf-8")
    total = sum((RUNTIME_AUDIO / f"{name}.mp3").stat().st_size for name in bundled)
    print(f"Bundled {len(bundled)}/{len(direction)} sounds ({total / 1024:.0f} KiB).")


if __name__ == "__main__":
    prepare_picnic_sounds()
